/**
 * `trickle-lite worker <command...>`, run in a Cloudflare Worker's directory, e.g.
 *
 *   trickle-lite worker npx wrangler deploy
 *
 * Copies the repository into trickle-lite's data folder with its TypeScript instrumented, adds an entry that
 * wraps the Worker's handlers so observations are sent after each request (see worker-runtime.ts), and runs
 * the command there, with the copy's wrangler config pointing at that entry. The repository itself is not modified.
 */
import fs from 'node:fs';
import path from 'node:path';
import { spawn } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { instrument } from './instrument.js';
import { syncShadow } from './shadow.js';
import { dataDir, findRoot, shouldInstrument, toKey } from './common.js';

const RUNTIME = path.join(path.dirname(fileURLToPath(import.meta.url)), 'worker-runtime.js');
const HANDLERS = ['fetch', 'scheduled', 'queue', 'email', 'tail', 'trace'];

const MAIN_RE = { toml: /^(\s*main\s*=\s*")([^"]+)(")/m, json: /("main"\s*:\s*")([^"]+)(")/ };

/** The wrangler config in `dir`, and its `main`. */
function wranglerConfig(dir: string): { file: string; text: string; re: RegExp; main: string } {
  for (const name of ['wrangler.jsonc', 'wrangler.json', 'wrangler.toml']) {
    const file = path.join(dir, name);
    if (!fs.existsSync(file)) continue;
    const text = fs.readFileSync(file, 'utf8');
    const re = name.endsWith('.toml') ? MAIN_RE.toml : MAIN_RE.json;
    const m = re.exec(text);
    if (m) return { file, text, re, main: m[2]! };
  }
  throw new Error(`no wrangler config with a "main" in ${dir}`);
}

function entrySource(mainImport: string, project: string): string {
  return `// Generated by trickle-lite: the Worker's own entry, with observations sent after each request.
import { flush } from ${JSON.stringify(RUNTIME)};
import worker from ${JSON.stringify(mainImport)};
export * from ${JSON.stringify(mainImport)};
const HANDLERS = ${JSON.stringify(HANDLERS)};
const wrap = (handler) => async function (event, env, ctx) {
  try { return await handler.call(this, event, env, ctx); }
  finally { try { ctx.waitUntil(flush(env, ${JSON.stringify(project)})); } catch {} }
};
export default worker && typeof worker === 'object'
  ? Object.fromEntries(Object.entries(worker).map(([k, v]) => [k, HANDLERS.includes(k) && typeof v === 'function' ? wrap(v) : v]))
  : worker;
`;
}

export async function worker(command: string[]): Promise<number> {
  if (!command.length) { process.stderr.write('trickle-lite worker: no command given (e.g. npx wrangler deploy)\n'); return 2; }
  const root = findRoot();
  const pkg = process.cwd();
  const config = wranglerConfig(pkg);
  const main = config.main;
  const overrides = new Map<string, string>();
  // Every project TypeScript file is instrumented; the bundler keeps the ones the Worker imports.
  const walk = (dir: string) => {
    for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
      if (e.name === 'node_modules' || e.name.startsWith('.')) continue;
      const abs = path.join(dir, e.name);
      if (e.isDirectory()) walk(abs);
      else if (shouldInstrument(abs, root)) {
        const out = instrument(fs.readFileSync(abs, 'utf8'), abs, toKey(root, abs));
        if (out) overrides.set(toKey(root, abs), out.code);
      }
    }
  };
  walk(root);
  const mainAbs = path.resolve(pkg, main);
  const entryRel = path.join(path.dirname(main), '__trickle_entry.mjs');
  const mainImport = './' + path.basename(mainAbs).replace(/\.[mc]?tsx?$/, '');
  overrides.set(toKey(root, path.resolve(pkg, entryRel)), entrySource(mainImport, process.env.TRICKLE_PROJECT || path.basename(root)));
  // In the copy only, the Worker's entry becomes the generated one.
  overrides.set(toKey(root, config.file), config.text.replace(config.re, (_, a: string, _m: string, c: string) => a + entryRel.split(path.sep).join('/') + c));
  const build = path.join(dataDir(root), 'worker');
  syncShadow(root, build, overrides, true);
  console.error(`trickle-lite: ${overrides.size - 1} files instrumented (types only); running in ${build}`);
  const cwd = path.join(build, path.relative(root, pkg));
  return new Promise((resolve) => {
    const child = spawn(command[0]!, command.slice(1), { stdio: 'inherit', cwd, shell: process.platform === 'win32' });
    child.on('error', (e) => { process.stderr.write(`trickle-lite: ${e.message}\n`); resolve(127); });
    child.on('close', (code) => resolve(code ?? 1));
  });
}
